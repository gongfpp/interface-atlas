export type AtlasSection =
  "title" | "art" | "notes" | "variants" | "controls" | "prompt";
export function atlasDesign(slug: string) {
  const index = ATLAS_DESIGNS.findIndex((d) => d[0] === slug);
  if (index < 0) throw new Error(`Missing atlas direction: ${slug}`);
  const [id, headline, zh, en, order, duration] = ATLAS_DESIGNS[index];
  return {
    id,
    headline,
    zh,
    en,
    order: order.split(" ") as AtlasSection[],
    duration,
    index,
  };
}
